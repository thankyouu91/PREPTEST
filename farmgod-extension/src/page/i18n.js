export function pickLanguage(preference) {
  if (preference && preference !== 'auto' && STRINGS[preference]) return preference;
  const locale = String(window.game_data?.locale || '').slice(0, 2);
  return STRINGS[locale] ? locale : 'int';
}

export function t(language) {
  return STRINGS[language] || STRINGS.int;
}

export const availableLanguages = () => Object.keys(STRINGS);
